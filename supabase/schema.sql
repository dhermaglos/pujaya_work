create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  avatar_url text,
  created_at timestamptz default now()
);
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text unique not null
);
create table if not exists public.auctions (
  id uuid primary key default gen_random_uuid(),
  seller_id uuid not null references auth.users(id),
  category_id bigint references public.categories(id),
  title text not null,
  description text not null,
  image_urls text[] default '{}',
  starting_price numeric(14,2) not null check (starting_price > 0),
  current_price numeric(14,2) not null check (current_price > 0),
  min_increment numeric(14,2) not null check (min_increment > 0),
  ends_at timestamptz not null,
  status text not null default 'active' check (status in ('active','finished')),
  winner_id uuid references auth.users(id),
  created_at timestamptz default now()
);
create table if not exists public.bids (
  id uuid primary key default gen_random_uuid(),
  auction_id uuid not null references public.auctions(id) on delete cascade,
  bidder_id uuid not null references auth.users(id),
  amount numeric(14,2) not null,
  created_at timestamptz default now()
);
create table if not exists public.favorites (
  user_id uuid references auth.users(id) on delete cascade,
  auction_id uuid references public.auctions(id) on delete cascade,
  created_at timestamptz default now(),
  primary key(user_id,auction_id)
);
insert into public.categories(name) values
