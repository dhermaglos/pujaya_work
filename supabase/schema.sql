on conflict(name) do nothing;

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.auctions enable row level security;
alter table public.bids enable row level security;
alter table public.favorites enable row level security;

create policy "profiles readable" on public.profiles for select using (true);
create policy "profile owner update" on public.profiles for update using (auth.uid()=id);
create policy "categories readable" on public.categories for select using (true);
create policy "auctions readable" on public.auctions for select using (true);
create policy "seller creates auction" on public.auctions for insert with check (auth.uid()=seller_id);
create policy "seller updates auction" on public.auctions for update using (auth.uid()=seller_id) with check (auth.uid()=seller_id);
create policy "seller deletes auction" on public.auctions for delete using (auth.uid()=seller_id);
create policy "bids readable" on public.bids for select using (true);
create policy "authenticated bid insert" on public.bids for insert with check (
  auth.uid()=bidder_id and exists (
    select 1 from public.auctions a where a.id=auction_id
    and a.seller_id <> auth.uid() and a.status='active'
    and a.ends_at > now() and amount >= a.current_price+a.min_increment
  )
);
create policy "favorites owner read" on public.favorites for select using (auth.uid()=user_id);
create policy "favorites owner insert" on public.favorites for insert with check (auth.uid()=user_id);
create policy "favorites owner delete" on public.favorites for delete using (auth.uid()=user_id);

